#!/usr/bin/env python3
"""Generate deterministic gzip include files for the flash-resident web pages."""

from __future__ import annotations

import argparse
import gzip
import hashlib
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
ASSETS = (
    (ROOT / "src/DashboardPage.cpp", "DASHBOARD", ROOT / "src/DashboardPageGzip.inc"),
    (ROOT / "src/ConfigurationPage.cpp", "CONFIGPAGE", ROOT / "src/ConfigurationPageGzip.inc"),
    (ROOT / "src/ProvisioningPage.cpp", "PROVISION", ROOT / "src/ProvisioningPageGzip.inc"),
)


def source_asset(path: Path, delimiter: str) -> bytes:
    text = path.read_text(encoding="utf-8")
    start_marker = f'R"{delimiter}('
    end_marker = f'){delimiter}";'
    start = text.index(start_marker) + len(start_marker)
    end = text.index(end_marker, start)
    return text[start:end].encode("utf-8")


def render_include(source: bytes) -> str:
    compressed = bytearray(gzip.compress(source, compresslevel=9, mtime=0))
    compressed[9] = 255  # Normalize the gzip OS byte across Python platforms.
    compressed = bytes(compressed)
    if gzip.decompress(compressed) != source:
        raise RuntimeError("gzip round-trip verification failed")
    lines = [
        "// Generated by tools/generate_web_assets.py; do not edit.",
        f"// source-bytes: {len(source)}",
        f"// source-sha256: {hashlib.sha256(source).hexdigest()}",
        f"// gzip-bytes: {len(compressed)}",
        f"// gzip-sha256: {hashlib.sha256(compressed).hexdigest()}",
    ]
    for offset in range(0, len(compressed), 16):
        chunk = compressed[offset : offset + 16]
        lines.append("  " + ", ".join(f"0x{value:02x}" for value in chunk) + ",")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if generated files differ")
    args = parser.parse_args()
    changed = False
    for source_path, delimiter, output_path in ASSETS:
        rendered = render_include(source_asset(source_path, delimiter))
        existing = output_path.read_text(encoding="ascii") if output_path.exists() else None
        if existing == rendered:
            continue
        changed = True
        if not args.check:
            output_path.write_text(rendered, encoding="ascii", newline="\n")
    if args.check and changed:
        parser.error("generated gzip assets are out of date")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
